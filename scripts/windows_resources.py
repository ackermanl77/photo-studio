"""Windows resources of the packaged PhotoStudio.exe (K6/K7), rendered by PhotoStudio.spec at build time.

- The version resource (Properties > Details) comes from ``app.__version__``, the single version source,
  so the exe never ships without a version or with a stale one.
- The application manifest is PyInstaller's default one (asInvoker, the supportedOS list, longPathAware,
  Common-Controls v6) plus ``activeCodePage`` UTF-8 -- the process's ANSI code page becomes UTF-8, so a
  library calling the narrow Win32 file APIs (``cv2.imread``/``cv2.imwrite``, some codecs) opens
  ``C:\\Fotos\\Año\\día.jpg`` instead of failing -- and ``dpiAwareness`` PerMonitorV2 (with the older
  ``dpiAware`` fallback), so the pywebview window is sharp on a scaled or mixed-DPI desktop.
- ``make_document_icon()`` draws the ``.photoproject`` document icon (``app/assets/photoproject.ico``) from
  the app icon; the spec embeds it as the exe's second icon group, which the installer's ``DefaultIcon``
  references as ``PhotoStudio.exe,1``.

Standard library only, except ``make_document_icon()`` (Pillow), which is a developer step: the generated
.ico is checked in.

    python scripts/windows_resources.py version          # prints app.__version__
    python scripts/windows_resources.py document-icon    # regenerates app/assets/photoproject.ico
"""
