import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLISHER = "MELEJ"
PRODUCT = "Photo Studio"
APP_ICON = os.path.join(ROOT, "app", "assets", "photostudio.ico")
DOCUMENT_ICON = os.path.join(ROOT, "app", "assets", "photoproject.ico")
ICON_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)

