def app_version() -> str:
    """``__version__`` read from app/__init__.py without importing the package."""
    with open(os.path.join(ROOT, "app", "__init__.py"), "r", encoding="utf-8") as handle:
        match = re.search(r'^__version__\s*=\s*"([^"]+)"', handle.read(), re.MULTILINE)
    if not match:
        raise RuntimeError("app/__init__.py defines no __version__")
    return match.group(1)


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """``"0.2.0"`` -> ``(0, 2, 0, 0)``: the four numbers VSVersionInfo needs."""
    parts = [int(part) for part in re.findall(r"\d+", version)[:4]]
    return tuple(parts + [0] * (4 - len(parts)))  # type: ignore[return-value]


def version_file_text(version: str) -> str:
    numbers = version_tuple(version)
    return _VERSION_TEMPLATE.format(numbers=repr(numbers), version=".".join(map(str, numbers)), publisher=PUBLISHER, product=PRODUCT)


def write_version_file(out_dir: str, version: str | None = None) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "photostudio_version.txt")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(version_file_text(version or app_version()))
    return path


def write_manifest(out_dir: str) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "photostudio.manifest")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(MANIFEST_XML)
    return path


def make_document_icon(app_icon: str = APP_ICON, out_path: str = DOCUMENT_ICON) -> str:
    """A white page with a folded corner and the app icon on it, at every Explorer size."""
    from PIL import Image, ImageDraw

    with Image.open(app_icon) as source:
        sizes = sorted(getattr(source, "info", {}).get("sizes", {source.size}), key=lambda size: size[0])
        source.size = sizes[-1]
        art = source.convert("RGBA")
    scale = 4
    side = 256 * scale
    page = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    draw = ImageDraw.Draw(page)
    left, top, right, bottom = int(side * 0.16), int(side * 0.04), int(side * 0.84), int(side * 0.96)
    fold = int(side * 0.2)
    outline = (90, 98, 112, 255)
    width = max(2, side // 64)
    body = [(left, top), (right - fold, top), (right, top + fold), (right, bottom), (left, bottom)]
    draw.polygon(body, fill=(250, 251, 253, 255), outline=outline, width=width)
    draw.polygon([(right - fold, top), (right - fold, top + fold), (right, top + fold)], fill=(214, 220, 230, 255), outline=outline, width=width)
    badge = int(side * 0.52)
    art = art.resize((badge, badge), Image.LANCZOS)
    page.alpha_composite(art, ((side - badge) // 2, int(side * 0.36)))
    page = page.resize((256, 256), Image.LANCZOS)
    page.save(out_path, format="ICO", sizes=[(size, size) for size in ICON_SIZES])
    return out_path


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "version"
    if command == "version":
        print(app_version())
    elif command == "document-icon":
        print(make_document_icon())
    else:
        raise SystemExit(f"unknown command {command!r} (version, document-icon)")
